def starmap(f):
    img = MAP.copy()
    tw = [[(4, 6)], [(10, 9), (4, 10)], [(9, 11), (7, 8)], [(10, 6)]][f]
    for (x, y) in tw:
        put(img, x, y, "l")
        for dx, dy in [(1, 0), (-1, 0), (0, 1), (0, -1)]:
            if get(img, x + dx, y + dy) == "A":
                put(img, x + dx, y + dy, "C" if f % 2 else "B")

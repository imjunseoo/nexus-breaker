def stone(f):
    img = STONE.copy()
    vein = {0: "B", 1: "C", 2: "F", 3: "C"}[f]
    img[img == K["F"]] = K[vein]
    heat = [(6, 3 - f % 2), (9, 2 + f % 2), (8, 4 - (f + 1) % 3)]
    if f >= 1:
        for i, (x, y) in enumerate(heat[: f + 0]):
            put(img, x, y, "F" if (i + f) % 2 else "C")
    if f == 2:
        put(img, 7, 9, "E")
    return img


ANIM["warm_stone"] = [stone(f) for f in range(4)]


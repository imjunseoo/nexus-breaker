def remote(f):
    img = REMOTE.copy()
    dim = {"D": "B", "F": "B", "E": "C"}
    lit = [(8, 7), (8, 9), (8, 11)]
    for i, (x, y) in enumerate(lit):
        k = get(img, x, y)

def build():
    out = []
    a = Asset("Assets/Art/UI/ui_panel.aseprite", 24, 24, ["panel"]); a.add(panel())
    a.slices.append(dict(name="ui_panel", rect=(0, 0, 24, 24), center=(6, 6, 12, 12))); out.append(a)
    a = Asset("Assets/Art/UI/ui_panel_dark.aseprite", 24, 24, ["panel_dark"]); a.add(panel_dark())
    a.slices.append(dict(name="ui_panel_dark", rect=(0, 0, 24, 24), center=(6, 6, 12, 12))); out.append(a)
    # multi-state files: one 1-frame tag per state/icon (code maps "file/tag")
    a = Asset("Assets/Art/UI/ui_button.aseprite", 24, 16, ["ui"])
    for n in ("normal", "hover", "pressed"):
        a.tag(n, [button(n)], 100)
    a.slices.append(dict(name="ui_button", rect=(0, 0, 24, 16), center=(5, 5, 14, 6))); out.append(a)
    a = Asset("Assets/Art/UI/ui_slot.aseprite", 20, 20, ["ui"])
    a.tag("empty", [slot(False)], 100)
    a.tag("selected", [slot(True)], 100)
    a.slices.append(dict(name="ui_slot", rect=(0, 0, 20, 20), center=(4, 4, 12, 12))); out.append(a)
    a = Asset("Assets/Art/UI/ui_bar.aseprite", 64, 8, ["ui"])
    a.tag("frame", [bar_frame()], 100)
    a.tag("fill", [bar_fill()], 100)
    a.slices.append(dict(name="ui_bar", rect=(0, 0, 64, 8), center=(2, 2, 60, 4))); out.append(a)
    a = Asset("Assets/Art/UI/ui_icons.aseprite", 16, 16, ["ui"])
    for n in ICON_ORDER:
        a.tag(n, [ICONS[n]], 100)
    out.append(a)
    a = Asset("Assets/Art/UI/ui_nut_small.aseprite", 8, 8, ["nut"]); a.add(NUT_SMALL); out.append(a)
    for x in out:
        x.preview_bg = (70, 66, 72)
    return out


if __name__ == "__main__":
    for a in build():
        if "--export" in sys.argv:
            export(a, "ui", s=6)
        else:
            write_previews(a, "ui", s=6)

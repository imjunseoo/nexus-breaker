def P(s, w):
    return parse(s, pad=w)


def frame_box(w, h, rings, centre, corner=None, round_=True):
    """rings: list of (top_left_key, bottom_right_key) from outside in. centre key fills the rest."""
    img = blank(w, h)
    img[:, :] = K[centre]
    for i, (tl, br) in enumerate(rings):
        for x in range(i, w - i):
            img[i, x] = K[tl]
            img[h - 1 - i, x] = K[br]
        for y in range(i, h - i):
            img[y, i] = K[tl]
            img[y, w - 1 - i] = K[br]
        # diagonal corners: bottom-left & top-right split
        img[h - 1 - i, i] = K[br] if i else K[tl]
        img[i, w - 1 - i] = K[br] if i else K[tl]
    if round_:
        for (x, y) in ((0, 0), (w - 1, 0), (0, h - 1), (w - 1, h - 1)):
            img[y, x] = T
    return img


def rivet(img, x, y):
    put(img, x, y, "k"); put(img, x + 1, y, "j"); put(img, x, y + 1, "j"); put(img, x + 1, y + 1, "g")


# ---------------------------------------------------------------- panel (rusted steel plate), border 6
def panel():
    img = frame_box(24, 24, [("1", "1"), ("j", "g"), ("i", "h"), ("i", "h"), ("i", "h"), ("g", "j")], "h")
    for (x, y) in ((2, 2), (20, 2), (2, 20), (20, 20)):
        rivet(img, x, y)
    for (x, y, k) in ((4, 2, "5"), (5, 3, "4"), (19, 21, "5"), (2, 18, "4"), (21, 4, "5")):
        put(img, x, y, k)
    return img


def panel_dark():
    img = frame_box(24, 24, [("1", "1"), ("h", "g"), ("g", "g"), ("g", "2"), ("2", "h"), ("1", "g")], "2")
    for (x, y) in ((2, 2), (20, 2), (2, 20), (20, 20)):
        put(img, x, y, "i"); put(img, x + 1, y + 1, "1")
    return img


# ---------------------------------------------------------------- button 24x16, border 5
def button(state):
    if state == "normal":
        rings = [("1", "1"), ("x", "t"), ("w", "u"), ("v", "u")]
        c = "v"
    elif state == "hover":
        rings = [("1", "1"), ("x", "u"), ("x", "v"), ("w", "v")]
        c = "w"
    else:
        rings = [("1", "1"), ("t", "u"), ("u", "v"), ("u", "v")]
        c = "u"
    img = frame_box(24, 16, rings, c)
    if state != "pressed":  # thick bottom lip
        for x in range(1, 23):
            img[14, x] = K["s"]
            img[13, x] = K["t"] if state == "normal" else K["u"]
        img[13, 1] = K["t"]; img[14, 1] = K["s"]
    else:  # pressed: whole face sits 1px lower -> top shadow row
        for x in range(1, 23):
            img[1, x] = K["s"]
            img[2, x] = K["t"]
    return img


# ---------------------------------------------------------------- slot 20x20, border 4
def slot(selected):
    if not selected:
        return frame_box(20, 20, [("1", "1"), ("i", "g"), ("h", "h"), ("1", "i")], "2")
    img = frame_box(20, 20, [("1", "1"), ("x", "v"), ("w", "w"), ("1", "x")], "2")
    for (x, y) in ((1, 1), (18, 1), (1, 18), (18, 18)):
        put(img, x, y, "l")
    return img


# ---------------------------------------------------------------- bar 64x8 (frame + neon fill)
def bar_frame():
    """64x8 frame for a 2px 9-slice: 1px outline + 1px bevel, inset trough inside."""
    img = blank(64, 8)
    img[:, :] = K["2"]
    for x in range(64):
        img[0, x] = K["1"]; img[7, x] = K["1"]
        img[1, x] = K["j"]; img[6, x] = K["g"]
    for y in range(8):
        img[y, 0] = K["1"]; img[y, 63] = K["1"]
    for y in range(1, 7):
        img[y, 1] = K["i"]; img[y, 62] = K["h"]
    img[1, 1] = K["k"]; img[6, 62] = K["h"]; img[6, 1] = K["h"]; img[1, 62] = K["i"]
    for x in range(2, 62):
        img[2, x] = K["1"]  # inner top shadow of the trough
    img[0, 0] = img[0, 63] = img[7, 0] = img[7, 63] = T
    return img


def bar_fill():
    """neon fill covering exactly the inside of the frame (x 2..61, y 2..5)."""
    img = blank(64, 8)
    for x in range(2, 62):
        img[2, x] = K["E"]
        img[3, x] = K["D"]
        img[4, x] = K["D"]
        img[5, x] = K["D"]
    return img


